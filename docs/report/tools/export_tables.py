"""Emit the report's data tables straight from the live analyzer.

The previous design document drifted from the code: it still documented a five-terminal
grammar whose FIRST/FIRST conflict had long since been factored away. Everything the
rubric asks to see -- token tables, regular expressions, grammar rules, the transformation
ledger, FIRST/FOLLOW, the LL(1) table, accept/reject verdicts -- is therefore generated
here into generated/*.tex and \\input by the report, so it cannot go stale.

    python tools/export_tables.py
"""

from __future__ import annotations

import argparse
import os
import sys
from collections import Counter
from pathlib import Path

from yaounde_analyzer.core import text as text_module
from yaounde_analyzer.core.analysis import (
    TOPIC_KEYWORDS,
    PreparedAnalyzer,
    analyze_tokens_and_parse,
    compute_statistics,
)
from yaounde_analyzer.core.corpus import validate_import
from yaounde_analyzer.core.lexicon import EntrySource
from yaounde_analyzer.core.specs import (
    load_demo_corpus_records,
    load_demo_grammar,
    load_demo_lexicon,
)

OUT = Path(__file__).resolve().parent.parent / "generated"
EOF = r"\$"

_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex(value: object) -> str:
    return "".join(_ESCAPES.get(ch, ch) for ch in str(value))


def write(name: str, body: str) -> None:
    (OUT / name).write_text(body.rstrip() + "\n", encoding="utf-8")
    print(f"  generated/{name}")


def facts(analyzer: PreparedAnalyzer, records: list[dict]) -> None:
    lexicon, grammar = analyzer.lexicon, analyzer.descriptive_grammar
    by_source = Counter(str(e.source) for e in lexicon.entries)
    accepted = sum(
        analyze_tokens_and_parse(r["raw_text"], analyzer)[1].accepted for r in records
    )
    values = {
        "LexiconTotal": len(lexicon.entries),
        "LexiconCorpus": by_source.get("corpus", 0),
        "LexiconDictionary": by_source.get("dictionary", 0),
        "LexiconMultiword": sum(1 for e in lexicon.entries if len(e.words) > 1),
        "TerminalCount": len(grammar.terminals),
        "NonterminalCount": len(grammar.nonterminals),
        "ProductionCount": len(grammar.productions),
        "ExecProductionCount": len(analyzer.grammar.productions),
        "LedgerSteps": len(analyzer.transformation_steps),
        "CorpusTotal": len(records),
        "CorpusAccepted": accepted,
        "CorpusRejected": len(records) - accepted,
        "CorpusAttested": sum(
            1 for r in records
            if r["source_kind"] == "field" and r["manual_transcription_attested"]
        ),
        "TopicCount": len(TOPIC_KEYWORDS),
        "OriginCount": len({str(c) for e in lexicon.entries for c in e.language_candidates}),
        "GrammarVersion": tex(grammar.version),
        "LexiconVersion": tex(lexicon.version),
    }
    lines = [r"% Generated by tools/export_tables.py -- do not edit."]
    lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in values.items()]
    write("facts.tex", "\n".join(lines))


def regex_table() -> None:
    rows = [
        ("WORD", text_module._WORD_RE.pattern,
         "Letters and combining accents, with internal apostrophes or hyphens"),
        ("NUMBER", text_module._NUMBER_RE.pattern, "A run of digits"),
        ("SPACE", text_module._SPACE_RE.pattern, "Horizontal whitespace only"),
        ("NEWLINE", text_module._NEWLINE_RE.pattern, "One or more line breaks"),
        ("PUNCTUATION", text_module._PUNCTUATION_RE.pattern,
         "Sentence and clause marks, including guillemets"),
    ]
    body = [
        r"\begin{table}[htbp]",
        r"\centering",
        r"\caption{Regular expressions driving the scanner, exported from \texttt{core/text.py}.}",
        r"\label{tab:regex}",
        r"\begin{tabular}{@{}l p{0.40\linewidth} p{0.32\linewidth}@{}}",
        r"\toprule",
        r"\textbf{Span kind} & \textbf{Regular expression} & \textbf{Matches} \\",
        r"\midrule",
    ]
    for kind, pattern, meaning in rows:
        # Allow a line break after every character: regexes have no natural
        # break points and would otherwise overflow the column.
        breakable = r"\allowbreak{}".join(tex(ch) for ch in pattern)
        body.append(rf"\texttt{{{kind}}} & \ttfamily\scriptsize {breakable} & {meaning} \\")
        body.append(r"\addlinespace")
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write("regexes.tex", "\n".join(body))


